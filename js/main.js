(function () {
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];
  const store = {
    get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  };

  /* Язык */
  const nodes = $$('[data-i18n]');
  const RU = {};
  nodes.forEach(n => { if (!(n.dataset.i18n in RU)) RU[n.dataset.i18n] = n.innerHTML; });
  function setLang(l) {
    nodes.forEach(n => { const k = n.dataset.i18n; n.innerHTML = l === 'kz' && KZ[k] ? KZ[k] : RU[k]; });
    document.documentElement.lang = l === 'kz' ? 'kk' : 'ru';
    $$('.lang button').forEach(b => b.classList.toggle('on', b.dataset.lang === l));
    store.set('aray-lang', l);
  }
  $$('.lang button').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
  if (store.get('aray-lang') === 'kz') setLang('kz');

  /* Заставка: один раз за визит */
  let seen = false;
  try { seen = sessionStorage.getItem('aray-seen'); sessionStorage.setItem('aray-seen', '1'); } catch (e) {}
  if (seen) { document.body.classList.add('noloader'); requestAnimationFrame(() => document.body.classList.add('ready')); }
  else setTimeout(() => document.body.classList.add('ready'), 1350);

  /* Меню */
  const burger = $('.burger');
  burger.addEventListener('click', () => document.body.classList.toggle('menu'));
  $$('.nav a').forEach(a => a.addEventListener('click', () => document.body.classList.remove('menu')));

  /* Прокрутка: шапка, прогресс, параллакс, кнопка WhatsApp */
  const header = $('.header'), bar = $('.progress'), fab = $('.fab'), pars = $$('[data-par]');
  let last = 0, tick = false;
  function onScroll() {
    const y = window.scrollY, max = document.documentElement.scrollHeight - innerHeight;
    header.classList.toggle('scrolled', y > 30);
    header.classList.toggle('hide', y > last && y > 500 && !document.body.classList.contains('menu'));
    bar.style.transform = 'scaleX(' + (max > 0 ? y / max : 0) + ')';
    fab.classList.toggle('show', y > 420);
    pars.forEach(p => {
      const r = p.getBoundingClientRect();
      if (r.bottom > -200 && r.top < innerHeight + 200) p.style.setProperty('--py', ((r.top + r.height / 2 - innerHeight / 2) * -parseFloat(p.dataset.par)).toFixed(1) + 'px');
    });
    last = y; tick = false;
  }
  addEventListener('scroll', () => { if (!tick) { tick = true; requestAnimationFrame(onScroll); } }, { passive: true });
  onScroll();

  /* Появление блоков и счетчики */
  const io = new IntersectionObserver(es => es.forEach(e => {
    if (!e.isIntersecting) return;
    e.target.classList.add('in');
    $$('[data-count]', e.target).forEach(count);
    io.unobserve(e.target);
  }), { threshold: 0.14, rootMargin: '0px 0px -6% 0px' });
  $$('[data-r]').forEach(n => io.observe(n));
  function count(el) {
    const to = +el.dataset.count, t0 = performance.now(), dur = 1400;
    (function step(t) {
      const p = Math.min(1, (t - t0) / dur);
      el.textContent = Math.round(to * (1 - Math.pow(1 - p, 3)));
      if (p < 1) requestAnimationFrame(step);
    })(t0);
  }

  /* Лента зон: перетаскивание мышью */
  $$('.rail').forEach(rail => {
    let down = false, sx = 0, sl = 0, moved = false;
    rail.addEventListener('mousedown', e => { down = true; moved = false; sx = e.pageX; sl = rail.scrollLeft; rail.style.scrollSnapType = 'none'; });
    addEventListener('mouseup', () => { if (down) { down = false; rail.style.scrollSnapType = ''; } });
    rail.addEventListener('mousemove', e => { if (!down) return; const dx = e.pageX - sx; if (Math.abs(dx) > 5) moved = true; rail.scrollLeft = sl - dx; });
    rail.addEventListener('click', e => { if (moved) e.preventDefault(); }, true);
    rail.addEventListener('dragstart', e => e.preventDefault());
  });

  /* Аккордеон */
  $$('.acc__btn').forEach(b => b.addEventListener('click', () => {
    const item = b.parentElement, open = item.classList.toggle('open');
    b.setAttribute('aria-expanded', open);
  }));

  /* Подсветка за курсором */
  const glow = $('.glow');
  if (glow && matchMedia('(hover:hover)').matches)
    addEventListener('mousemove', e => { glow.style.transform = 'translate(' + e.clientX + 'px,' + e.clientY + 'px)'; }, { passive: true });
})();
